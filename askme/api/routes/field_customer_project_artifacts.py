    @app.get(
        "/api/field/customer-projects/{identifier}/export",
        tags=["Field Operations"],
        response_model=CustomerProjectPackageExportResponse,
        response_model_exclude_none=True,
    )
    async def field_customer_project_export(identifier: str, request: Request) -> JSONResponse:
        """Export a reusable customer project handoff package."""
        try:
            failure, auth_body = project_read_auth(request)
            if failure is not None:
                return failure
            scope = operator_project_scope(auth_body)
            root = site_profile_root()
            scope_failure = customer_project_scope_failure(root, identifier, scope)
            if scope_failure is not None:
                return scope_failure
            result = export_customer_project_package(
                root,
                identifier,
                output_root=package_output_root(),
            )
            if result.get("accepted") and not scope_allows(scope, scope_item_from_package(result)):
                return project_scope_forbidden()
            if result.get("accepted"):
                result = CustomerProjectPackageExportResponse.model_validate(
                    result
                ).model_dump(mode="python")
            return mission_json(result, status_code=200 if result.get("accepted") else 404)
        except Exception as exc:
            logger.error("Field customer project export endpoint failed: %s", exc)
            return mission_json({"error": str(exc)}, status_code=500)

